def unquote(m):
    parts = re.findall(r'"((?:[^"\\]|\\.)*)"', m)
    return ''.join(parts).replace('\\n', '\n').replace('\\t', '\t').replace('\\r', '\r').replace('\\"', '"').replace('\\\\', '\\')

def quote(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\t', '\\t') + '"'

