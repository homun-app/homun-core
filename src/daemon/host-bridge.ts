// HostBridge: le API che nel processo Electron vivevano nel main (notifiche
// native, safeStorage, screen) qui passano da un bridge — con la UI aperta
// diventano RPC verso il main Electron, senza UI degradano in modo doc:
// notifica via osascript, vault bloccato (mai chiavi in chiaro), scale factor
// retina di default (coerente con gli screenshot nativi 2x).
import { execFile } from 'node:child_process'
import { setScaleFactorProvider } from '../main/computeruse'
import { setSafeStorage, type SafeStorageLike } from '../main/vault'

/** notifica macOS senza Electron: display notification di osascript. */
export function osascriptNotify(title: string, body: string): void {
  const esc = (s: string) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')
  execFile('osascript', ['-e', `display notification "${esc(body)}" with title "${esc(title)}"`], () => undefined)
}

export interface HostBridgeDeps {
  /** RPC verso la UI; null/throw se la UI non è connessa. */
  callUi(method: string, params?: unknown[]): Promise<unknown>
  hasUi(): boolean
}

/** Fase 14 (punto 5): il generatore di PDF via UI (printToPDF su finestra nascosta). */
let printToPdfFn: ((html: string) => Promise<Buffer>) | null = null

/** Registra (o togli) il generatore di PDF del bridge. */
export function setPrintToPdf(fn: ((html: string) => Promise<Buffer>) | null): void {
  printToPdfFn = fn
}

/** Il generatore di PDF registrato, se c'è (null = senza UI: l'export dice di aprire SandBot). */
export function getPrintToPdf(): ((html: string) => Promise<Buffer>) | null {
  return printToPdfFn
}

/** safeStorage proxy verso la UI: disponibile solo a finestra aperta. */
export function uiSafeStorage(deps: HostBridgeDeps): SafeStorageLike {
  return {
    isEncryptionAvailable: () => deps.hasUi(),
    encryptString: async (plain: string) => Buffer.from(String(await deps.callUi('host.safeStorage.encrypt', [plain])), 'base64'),
    decryptString: async (encrypted: Buffer) => String(await deps.callUi('host.safeStorage.decrypt', [encrypted.toString('base64')]))
  }
}

/**
 * Collega il bridge al runtime: safeStorage del vault, scale factor del
 * computer use (cache 60s), notifiche (fase 6: titolo e corpo già decisi
 * dalle regole di soppressione del daemon, agent-done/agent-needs-input).
 * Fase 16b (S1.2): notify accetta un openGroupId — il click sulla notifica
 * apre la SQUADRA (riepilogo del coordinatore), non la chat privata.
 */
export function attachHostBridge(deps: HostBridgeDeps): {
  notify(title: string, body: string, openGroupId?: number): void
  refreshScale(): void
} {
  setSafeStorage(uiSafeStorage(deps))

  /**
   * Fase 14 (punto 5): il PDF lo genera la UI (Electron printToPDF su una
   * finestra nascosta con l'HTML autonomo del documento). Il daemon lo chiama
   * via RPC host.printToPDF; senza UI la funzione non c'è e l'export dice di
   * aprire SandBot o scegliere html.
   */
  setPrintToPdf(async (html: string) => {
    // fase 17c (C3): errore DUPLICE (l'esportazione è anche un tool): testo
    // inglese al modello dentro il wrapper del loop, UiText per la UI al confine RPC
    if (!deps.hasUi()) {
      const { ui, UI } = await import('../main/ui-language')
      const { UiError } = await import('../shared/ui-text')
      throw new UiError('the PDF is generated by the Homun window: open it and try again, or export as html', ui(UI.rpcPdfNeedsWindow))
    }
    const b64 = await deps.callUi('host.printToPDF', [html])
    return Buffer.from(String(b64), 'base64')
  })

  let scaleFactor = 2
  setScaleFactorProvider(() => scaleFactor)
  const refreshScale = (): void => {
    if (!deps.hasUi()) return
    deps.callUi('host.screen.scaleFactor')
      .then((v) => {
        if (typeof v === 'number' && v > 0) scaleFactor = v
      })
      .catch(() => undefined)
  }
  const refreshTimer = setInterval(refreshScale, 60_000)
  refreshTimer.unref()

  return {
    refreshScale,
    /**
     * Notifica nativa con la UI aperta (il click riporta alla finestra — e
     * alla squadra, con openGroupId), osascript senza UI.
     */
    notify(title: string, body: string, openGroupId?: number): void {
      if (deps.hasUi()) {
        void deps.callUi('host.notify', [title, body, ...(openGroupId !== undefined ? [openGroupId] : [])]).catch(() =>
          osascriptNotify(title, body)
        )
      } else {
        osascriptNotify(title, body)
      }
    }
  }
}
